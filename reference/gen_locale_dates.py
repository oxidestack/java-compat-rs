#!/usr/bin/env python3
"""Writes src/text/locale_dates.rs from the recorded locale_dates.json, week_data.json and jdk_languages.json fixtures: tests/fixtures/full
(JDK 26, LocaleData::Full), tests/fixtures/jdk21 (Keycloak 26.5.3's JDK 21, LocaleData::FullJdk21) and, for week data
only, tests/fixtures/javabase (LocaleData::JavaBase).

Locales whose calendar is not Gregorian (th_TH: BuddhistCalendar) are left out: the crate has no such calendar.

Run: reference/gen_locale_dates.py   (after reference/run.sh localedates)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SYMBOL_KEYS = [("eras", 2), ("months", 12), ("shortMonths", 12), ("standaloneMonths", 12), ("standaloneShortMonths", 12),
               ("weekdays", 7), ("shortWeekdays", 7), ("ampm", 2)]
PATTERN_KEYS = [("date", 4), ("time", 4), ("dateTime", 16)]


def rs(s):
    out = []
    for c in s:
        if c in '"\\':
            out.append("\\" + c)
        elif 0x20 <= ord(c) < 0x7f:
            out.append(c)
        else:
            out.append("\\u{%x}" % ord(c))
    return '"' + "".join(out) + '"'


def arr(xs):
    return "[" + ", ".join(rs(x) for x in xs) + "]"


def load(provider, name):
    return json.loads((ROOT / "tests/fixtures" / provider / name).read_text(encoding="utf-8"))


class Pool:
    def __init__(self):
        self.items, self.index = [], {}

    def add(self, item):
        if item not in self.index:
            self.index[item] = len(self.items)
            self.items.append(item)
        return self.index[item]


def main():
    providers = [("full", "JDK26"), ("jdk21", "JDK21")]
    symbols, patterns, zone_rows, zone_strings = Pool(), Pool(), Pool(), Pool()
    zone_ids, tables = None, {}
    for provider, name in providers:
        table = []
        for r in load(provider, "locale_dates.json"):
            if r["calendar"] != "GregorianCalendar":
                continue
            ids = [z[0] for z in r["zones"]]
            assert zone_ids in (None, ids)
            zone_ids = ids
            for key, n in SYMBOL_KEYS + PATTERN_KEYS:
                assert len(r[key]) == n, (r["locale"], key)
            sym = tuple(tuple(r[k]) for k, _ in SYMBOL_KEYS)
            pat = tuple(tuple(r[k]) for k, _ in PATTERN_KEYS)
            zones = tuple(zone_strings.add(s) for z in r["zones"] for s in z[1:])
            table.append((r["locale"], symbols.add(sym), patterns.add(pat), zone_rows.add(zones)))
        table.sort()
        tables[name] = table
    weeks = {}
    for provider, name in [("full", "JDK26"), ("jdk21", "JDK21"), ("javabase", "JAVABASE")]:
        weeks[name] = sorted((r, f, m) for r, f, m in load(provider, "week_data.json"))

    o = ["// @generated by reference/gen_locale_dates.py from tests/fixtures/{full,jdk21,javabase}/{locale_dates,week_data,jdk_languages}.json.",
         "// Do not edit.",
         "//! Date locale data (`DateFormatSymbols`, standalone month names, `DateFormat` style patterns, zone display names)",
         "//! of every locale the JDK has for the languages Keycloak 26.5.3 ships theme messages for, plus English and French,",
         "//! as JDK 26 (`JDK26`) and Keycloak's JDK 21 (`JDK21`, CLDR 42) give them; and each region's week data.",
         "",
         "use super::symbols::{DateData, DatePatterns};",
         ""]
    o.append(f"pub(crate) static SYMBOLS: [DateData; {len(symbols.items)}] = [")
    for s in symbols.items:
        d = dict(zip([k for k, _ in SYMBOL_KEYS], s))
        o.append("    DateData { eras: %s, months: %s, short_months: %s, standalone_months: %s, standalone_short_months: %s, "
                 "weekdays: %s, short_weekdays: %s, am_pm: %s }," % (
                     arr(d["eras"]), arr(d["months"]), arr(d["shortMonths"]), arr(d["standaloneMonths"]),
                     arr(d["standaloneShortMonths"]), arr(d["weekdays"]), arr(d["shortWeekdays"]), arr(d["ampm"])))
    o.append("];")
    o.append("")
    o.append(f"pub(crate) static PATTERNS: [DatePatterns; {len(patterns.items)}] = [")
    for p in patterns.items:
        d = dict(zip([k for k, _ in PATTERN_KEYS], p))
        o.append("    DatePatterns { date: %s, time: %s, date_time: %s }," % (arr(d["date"]), arr(d["time"]), arr(d["dateTime"])))
    o.append("];")
    o.append("")
    o.append("/// The zones whose names `ZONE_ROWS` carry, in their order.")
    o.append(f"pub(crate) static ZONE_IDS: [&str; {len(zone_ids)}] = {arr(zone_ids)};")
    o.append("")
    o.append(f"pub(crate) static ZONE_STRINGS: [&str; {len(zone_strings.items)}] = [")
    for s in zone_strings.items:
        o.append(f"    {rs(s)},")
    o.append("];")
    o.append("")
    o.append("/// Per zone of `ZONE_IDS`: standard long, standard short, daylight long, daylight short (`ZONE_STRINGS` indices).")
    o.append(f"pub(crate) static ZONE_ROWS: [[u16; {4 * len(zone_ids)}]; {len(zone_rows.items)}] = [")
    for row in zone_rows.items:
        o.append("    [" + ", ".join(str(i) for i in row) + "],")
    o.append("];")
    for name, table in tables.items():
        o.append("")
        o.append("/// (`Locale.toString()`, symbols, patterns, zone names), sorted by locale.")
        o.append(f"pub(crate) static {name}: [(&str, u16, u16, u16); {len(table)}] = [")
        for (l, s, p, z) in table:
            o.append(f"    ({rs(l)}, {s}, {p}, {z}),")
        o.append("];")
    for name, table in weeks.items():
        o.append("")
        o.append("/// (region, firstDayOfWeek, minimalDaysInFirstWeek) of `Calendar.getInstance(new Locale(\"\", region))`, sorted;")
        o.append("/// `XX` stands for any region the JDK does not know.")
        o.append(f"pub(crate) static WEEKS_{name}: [(&str, u8, u8); {len(table)}] = [")
        for (r, f, m) in table:
            o.append(f"    ({rs(r)}, {f}, {m}),")
        o.append("];")
    for provider, name in providers:
        languages = sorted(load(provider, "jdk_languages.json"))
        o.append("")
        o.append("/// The languages the JDK has locale data for (any other formats with root data), sorted.")
        o.append(f"pub(crate) static LANGUAGES_{name}: [&str; {len(languages)}] = {arr(languages)};")
    (ROOT / "src/text/locale_dates.rs").write_text("\n".join(o) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
