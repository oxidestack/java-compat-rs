#!/usr/bin/env python3
"""Writes src/text/locale_numbers.rs from the recorded locale_numbers.json fixtures: tests/fixtures/full (JDK 26,
LocaleData::Full) and tests/fixtures/jdk21 (Keycloak 26.5.3's JDK 21, LocaleData::FullJdk21).

Run: reference/gen_locale_numbers.py   (after reference/run.sh localenumbers)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SYMBOL_KEYS = ["zero", "grouping", "decimal", "perMill", "percent", "digit", "patternSeparator", "infinity", "nan", "minus",
               "currencySymbol", "intlCurrencySymbol", "monetaryDecimal", "monetaryGrouping", "exponent", "minusText",
               "percentText", "perMillText"]


def rs(s):
    out = []
    for c in s:
        if c in '"\\':
            out.append("\\" + c)
        elif 0x20 <= ord(c) < 0x7f:
            out.append(c)
        else:
            out.append("\\u{%x}" % ord(c))
    return '"' + "".join(out) + '"'


def ch(s):
    assert len(s) == 1, s
    return "'" + rs(s)[1:-1].replace("'", "\\'") + "'"


def main():
    providers = [("full", "JDK26"), ("jdk21", "JDK21")]
    symbols, patterns, tables = [], [], {}
    sym_index, pat_index = {}, {}
    for provider, name in providers:
        rows = json.loads((ROOT / "tests/fixtures" / provider / "locale_numbers.json").read_text(encoding="utf-8"))
        table = []
        for r in rows:
            sym = tuple(r[k] for k in SYMBOL_KEYS)
            inst = {i["kind"]: i for i in r["instances"]}
            pat = (tuple(inst[k]["pattern"] for k in ("number", "integer", "currency", "percent")),
                   inst["currency"]["minFrac"], inst["currency"]["maxFrac"])
            if sym not in sym_index:
                sym_index[sym] = len(symbols)
                symbols.append(sym)
            if pat not in pat_index:
                pat_index[pat] = len(patterns)
                patterns.append(pat)
            table.append((r["locale"], sym_index[sym], pat_index[pat]))
        table.sort()
        tables[name] = table
    o = ["// @generated by reference/gen_locale_numbers.py from tests/fixtures/{full,jdk21}/locale_numbers.json. Do not edit.",
         "//! Number locale data (`DecimalFormatSymbols`, `NumberFormat` instance patterns) of every locale the JDK has for",
         "//! the languages Keycloak 26.5.3 ships theme messages for, plus English and French, as JDK 26 (`JDK26`) and",
         "//! Keycloak's JDK 21 (`JDK21`, CLDR 42) give them.",
         "",
         "use super::symbols::{NumberData, Patterns};",
         ""]
    o.append(f"pub(crate) static SYMBOLS: [NumberData; {len(symbols)}] = [")
    for s in symbols:
        d = dict(zip(SYMBOL_KEYS, s))
        o.append("    NumberData { zero: %s, grouping: %s, decimal: %s, per_mill: %s, percent: %s, digit: %s, pattern_separator: %s, "
                 "infinity: %s, nan: %s, minus: %s, currency_symbol: %s, intl_currency_symbol: %s, monetary_decimal: %s, "
                 "monetary_grouping: %s, exponent: %s, minus_text: %s, percent_text: %s, per_mill_text: %s }," % (
                     ch(d["zero"]), ch(d["grouping"]), ch(d["decimal"]), ch(d["perMill"]), ch(d["percent"]), ch(d["digit"]),
                     ch(d["patternSeparator"]), rs(d["infinity"]), rs(d["nan"]), ch(d["minus"]), rs(d["currencySymbol"]),
                     rs(d["intlCurrencySymbol"]), ch(d["monetaryDecimal"]), ch(d["monetaryGrouping"]), rs(d["exponent"]),
                     rs(d["minusText"]), rs(d["percentText"]), rs(d["perMillText"])))
    o.append("];")
    o.append("")
    o.append(f"pub(crate) static PATTERNS: [Patterns; {len(patterns)}] = [")
    for (ps, mn, mx) in patterns:
        o.append("    Patterns { patterns: [%s], currency_min_frac: %d, currency_max_frac: %d }," % (
            ", ".join(rs(p) for p in ps), mn, mx))
    o.append("];")
    for name, table in tables.items():
        o.append("")
        o.append(f"/// (`Locale.toString()`, symbols, patterns), sorted by locale.")
        o.append(f"pub(crate) static {name}: [(&str, u16, u8); {len(table)}] = [")
        for (l, s, p) in table:
            o.append(f"    ({rs(l)}, {s}, {p}),")
        o.append("];")
    (ROOT / "src/text/locale_numbers.rs").write_text("\n".join(o) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
