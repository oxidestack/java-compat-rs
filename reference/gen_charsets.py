#!/usr/bin/env python3
"""Writes src/charset_data.rs: Java's EUC-JP and Big5 encoders as (char, bytes) tables, generated from Unicode's
mapping files in reference/unicode/ (JIS0208.TXT, JIS0212.TXT, BIG5.TXT; Unicode License v3, see
reference/unicode/README.md) plus the JDK-specific mappings listed below.

The JDK recording (tests/fixtures/{full,javabase,jdk21}/charsets.json, reference/src/CharsetFixtures.java) is only
the check: the generated tables must equal it entry for entry, or this script fails without writing anything.

Run: reference/gen_charsets.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
UNICODE = ROOT / "reference/unicode"

# Where Java's encoders differ from Unicode's mapping files. Each entry was observed in JDK 21.0.12.1 (arm64
# eclipse-temurin:21-jdk) and is part of the recorded fixtures.
#   EUC-JP, JIS X 0208 0x2140 (bytes A1C0): JIS0208.TXT maps U+005C REVERSE SOLIDUS; Java encodes U+FF3C FULLWIDTH
#     REVERSE SOLIDUS there and U+005C as the ASCII byte 0x5C.
#   EUC-JP, JIS X 0208 0x213D (A1BD): JIS0208.TXT maps U+2015 HORIZONTAL BAR; Java encodes U+2014 EM DASH there and
#     U+2015 is unmappable.
#   EUC-JP, JIS X 0212 0x2237 (8FA2B7): JIS0212.TXT maps U+007E TILDE; Java encodes U+FF5E FULLWIDTH TILDE there and
#     U+007E as the ASCII byte 0x7E.
#   EUC-JP, U+00A5 YEN SIGN and U+203E OVERLINE: not in the Unicode files; Java encodes them as the single bytes 0x5C
#     and 0x7E (the JIS X 0201 Roman meaning of those bytes).
# Big5 needs none: BIG5.TXT, without its codes mapped to U+FFFD, is exactly Java's Big5 encoder.
EUC_JP_REMAP = {0x005C: 0xFF3C, 0x2015: 0x2014, 0x007E: 0xFF5E}
EUC_JP_ADD = {0x00A5: 0x5C, 0x203E: 0x7E}

# `Charset.aliases()` of each charset as Java reports it (observed output, checked against the fixtures), sorted.
ALIASES = {
    "EUC-JP": ["Extended_UNIX_Code_Packed_Format_for_Japanese", "csEUCPkdFmtjapanese", "euc_jp", "eucjis", "eucjp",
               "x-euc-jp", "x-eucjp"],
    "Big5": ["csBig5"],
}


def read_mapping(name, cols):
    """(code, unicode) pairs of a Unicode mapping file: the given hex columns of every non-comment line."""
    out = []
    for line in (UNICODE / name).read_text(encoding="utf-8").splitlines():
        fields = line.split("#", 1)[0].split()
        if fields:
            out.append(tuple(int(fields[c], 16) for c in cols))
    return out


def euc_jp():
    """EUC-JP: JIS X 0201 katakana (U+FF61..U+FF9F) as 8E A1..DF, JIS X 0208 as its two bytes with the high bits set,
    JIS X 0212 as 8F and two such bytes. A char in both JIS X 0208 and JIS X 0212 takes the JIS X 0208 code."""
    m = {}
    for cp in range(0xFF61, 0xFFA0):
        m[cp] = 0x8E00 | (cp - 0xFF61 + 0xA1)
    for jis, cp in read_mapping("JIS0208.TXT", (1, 2)):
        m.setdefault(cp, jis | 0x8080)
    for jis, cp in read_mapping("JIS0212.TXT", (0, 1)):
        m.setdefault(cp, 0x8F0000 | jis | 0x8080)
    for old, new in EUC_JP_REMAP.items():
        assert new not in m, hex(new)
        m[new] = m.pop(old)
    for cp, b in EUC_JP_ADD.items():
        assert cp not in m, hex(cp)
        m[cp] = b
    return m


def big5():
    """Big5: the two bytes as BIG5.TXT gives them; its codes mapped to U+FFFD are unmappable."""
    m = {}
    for b, cp in read_mapping("BIG5.TXT", (0, 1)):
        if cp != 0xFFFD:
            assert cp not in m, hex(cp)
            m[cp] = b
    return m


def check(tables):
    """The generated tables against the JDK recording: every BMP char that is neither ASCII-as-itself nor `?`."""
    rows = json.loads((ROOT / "tests/fixtures/jdk21/charsets.json").read_text(encoding="utf-8"))
    for p in ("full", "javabase"):
        assert json.loads((ROOT / "tests/fixtures" / p / "charsets.json").read_text(encoding="utf-8")) == rows, p
    assert [r["canonical"] for r in rows] == list(tables), [r["canonical"] for r in rows]
    bad = []
    for r in rows:
        assert r["supported"] and r["replacement"] == "3f" and not r["supplementary"], r["name"]
        assert r["aliases"] == ALIASES[r["canonical"]], r["aliases"]
        jdk = {cp: int(hx, 16) for cp, hx in r["map"]}
        ours = tables[r["canonical"]]
        for cp in sorted(set(jdk) | set(ours)):
            if jdk.get(cp) != ours.get(cp):
                bad.append(f"{r['canonical']} U+{cp:04X}: JDK {jdk.get(cp)!r}, generated {ours.get(cp)!r}")
    if bad:
        raise SystemExit("generated tables differ from the JDK recording:\n" + "\n".join(bad))


def main():
    tables = {"EUC-JP": euc_jp(), "Big5": big5()}
    for m in tables.values():
        for cp, b in m.items():
            assert cp >= 0x80 and 1 <= (b.bit_length() + 7) // 8 <= 3, (cp, b)
    check(tables)
    o = ["// @generated by reference/gen_charsets.py from Unicode's mapping files",
         "// reference/unicode/{JIS0208,JIS0212,BIG5}.TXT (Unicode License v3) and the JDK-specific mappings the",
         "// generator lists. Do not edit.",
         "//! `String.getBytes(charset)` of every BMP char under Java's EUC-JP and Big5 encoders, where it is neither the",
         "//! ASCII char itself nor the replacement `?` (no supplementary code point is encodable in either).",
         ""]
    for canonical, m in tables.items():
        ident = canonical.upper().replace("-", "_")
        entries = [f"(0x{cp:04x},0x{m[cp]:x})" for cp in sorted(m)]
        o.append(f"/// {canonical}: (char, bytes as a big-endian number), sorted by char.")
        o.append(f"pub(crate) static {ident}: [(u16, u32); {len(entries)}] = [")
        for i in range(0, len(entries), 8):
            o.append("    " + ",".join(entries[i:i + 8]) + ",")
        o.append("];")
        o.append("")
        aliases = ALIASES[canonical]
        o.append(f"/// {canonical}'s aliases (`Charset.aliases()`), sorted.")
        o.append(f"pub(crate) static {ident}_ALIASES: [&str; {len(aliases)}] = [" + ", ".join(
            '"%s"' % a for a in aliases) + "];")
        o.append("")
    (ROOT / "src/charset_data.rs").write_text("\n".join(o), encoding="utf-8")


if __name__ == "__main__":
    main()
