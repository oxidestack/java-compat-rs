#!/usr/bin/env python3
"""Writes src/util/currency_data.rs from the recorded currency.json fixtures: tests/fixtures/full (JDK 26,
LocaleData::Full), tests/fixtures/jdk21 (Keycloak 26.5.3's JDK 21, LocaleData::FullJdk21) and tests/fixtures/javabase
(the trimmed JDK, LocaleData::JavaBase). The codes and the region table are the same in all three (checked).

Run: reference/gen_currency.py   (after reference/run.sh currency)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent


def rs(s):
    out = []
    for c in s:
        if c in '"\\':
            out.append("\\" + c)
        elif 0x20 <= ord(c) < 0x7f:
            out.append(c)
        else:
            out.append("\\u{%x}" % ord(c))
    return '"' + "".join(out) + '"'


def main():
    providers = [("full", "JDK26"), ("jdk21", "JDK21"), ("javabase", "JAVABASE")]
    data = {p: json.loads((ROOT / "tests/fixtures" / p / "currency.json").read_text(encoding="utf-8")) for p, _ in providers}
    codes, countries = data["full"]["codes"], data["full"]["countries"]
    for p, _ in providers:
        assert data[p]["codes"] == codes and data[p]["countries"] == countries, p
        assert sorted(c[0] for c in data[p]["codes"]) == data[p]["available"], p
    sets, set_index, tables = [], {}, {}
    for p, name in providers:
        table = []
        for row in data[p]["symbols"]:
            key = tuple(sorted(row["symbols"].items()))
            if key not in set_index:
                set_index[key] = len(sets)
                sets.append(key)
            table.append((row["locale"], set_index[key]))
        tables[name] = sorted(table)
    o = ["// @generated by reference/gen_currency.py from tests/fixtures/{full,jdk21,javabase}/currency.json. Do not edit.",
         "//! `java.util.Currency` data: the codes `Currency.getInstance(String)` accepts, each region's currency, and",
         "//! `getSymbol(locale)` in every locale of the number-data languages, root and an unknown language (`xx`), as",
         "//! JDK 26 (`JDK26`), Keycloak's JDK 21 (`JDK21`) and the trimmed JDK (`JAVABASE`) give them.",
         "",
         f"/// (code, default fraction digits (-1 for pseudo-currencies), numeric code), sorted by code.",
         f"pub(crate) static CODES: [(&str, i8, u16); {len(codes)}] = ["]
    for code, frac, num in codes:
        o.append(f"    ({rs(code)}, {frac}, {num}),")
    o.append("];")
    o.append("")
    o.append("/// (region, its currency's code or \"\" for none), sorted by region: every region `Currency.getInstance(Locale)`")
    o.append("/// accepts; any other throws.")
    o.append(f"pub(crate) static REGIONS: [(&str, &str); {len(countries)}] = [")
    for cc, code in countries:
        o.append(f"    ({rs(cc)}, {rs(code or '')}),")
    o.append("];")
    o.append("")
    o.append("/// Symbol sets: (code, symbol) where `getSymbol(locale)` is not the code itself, sorted by code.")
    o.append(f"pub(crate) static SYMBOL_SETS: [&[(&str, &str)]; {len(sets)}] = [")
    for s in sets:
        o.append("    &[" + ", ".join(f"({rs(c)}, {rs(v)})" for c, v in s) + "],")
    o.append("];")
    for name, table in tables.items():
        o.append("")
        o.append("/// (`Locale.toString()`, symbol set), sorted by locale.")
        o.append(f"pub(crate) static {name}: [(&str, u16); {len(table)}] = [")
        for (l, i) in table:
            o.append(f"    ({rs(l)}, {i}),")
        o.append("];")
    (ROOT / "src/util/currency_data.rs").write_text("\n".join(o) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
