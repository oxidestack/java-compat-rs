// Generates java-compat-rs src/regex/tables.rs from the running JDK's observable behaviour:
// Character.getType / UnicodeScript.of / UnicodeBlock.of per code point, the public UnicodeScript.forName and
// UnicodeBlock.forName name lookups, java.util.regex \p{...} membership for the binary and java* properties, and
// the code points a case-insensitive literal or one-char class matches. No JDK source is read.
import java.util.*;
import java.util.function.IntPredicate;
import java.util.regex.Pattern;

public class RegexTables {
    static final StringBuilder out = new StringBuilder();
    static final String[] GC = new String[32];
    static {
        GC[Character.UNASSIGNED] = "Cn"; GC[Character.UPPERCASE_LETTER] = "Lu"; GC[Character.LOWERCASE_LETTER] = "Ll";
        GC[Character.TITLECASE_LETTER] = "Lt"; GC[Character.MODIFIER_LETTER] = "Lm"; GC[Character.OTHER_LETTER] = "Lo";
        GC[Character.NON_SPACING_MARK] = "Mn"; GC[Character.ENCLOSING_MARK] = "Me"; GC[Character.COMBINING_SPACING_MARK] = "Mc";
        GC[Character.DECIMAL_DIGIT_NUMBER] = "Nd"; GC[Character.LETTER_NUMBER] = "Nl"; GC[Character.OTHER_NUMBER] = "No";
        GC[Character.SPACE_SEPARATOR] = "Zs"; GC[Character.LINE_SEPARATOR] = "Zl"; GC[Character.PARAGRAPH_SEPARATOR] = "Zp";
        GC[Character.CONTROL] = "Cc"; GC[Character.FORMAT] = "Cf"; GC[Character.PRIVATE_USE] = "Co"; GC[Character.SURROGATE] = "Cs";
        GC[Character.DASH_PUNCTUATION] = "Pd"; GC[Character.START_PUNCTUATION] = "Ps"; GC[Character.END_PUNCTUATION] = "Pe";
        GC[Character.CONNECTOR_PUNCTUATION] = "Pc"; GC[Character.OTHER_PUNCTUATION] = "Po"; GC[Character.MATH_SYMBOL] = "Sm";
        GC[Character.CURRENCY_SYMBOL] = "Sc"; GC[Character.MODIFIER_SYMBOL] = "Sk"; GC[Character.OTHER_SYMBOL] = "So";
        GC[Character.INITIAL_QUOTE_PUNCTUATION] = "Pi"; GC[Character.FINAL_QUOTE_PUNCTUATION] = "Pf";
    }

    interface Key { int of(int cp); }

    static void runs(String name, Key key) {
        out.append("pub(crate) static ").append(name).append(": &[(u32, u32, u16)] = &[\n");
        int start = 0, cur = key.of(0), n = 0;
        for (int cp = 1; cp <= 0x110000; cp++) {
            int k = cp <= 0x10FFFF ? key.of(cp) : -2;
            if (k != cur) {
                if (cur >= 0) { out.append(String.format("(0x%X,0x%X,%d),", start, cp - 1, cur)); if (++n % 8 == 0) out.append('\n'); }
                start = cp; cur = k;
            }
        }
        out.append("\n];\n\n");
    }

    static String ranges(IntPredicate p) {
        StringBuilder b = new StringBuilder("&[");
        int start = -1;
        for (int cp = 0; cp <= 0x110000; cp++) {
            boolean in = cp <= 0x10FFFF && p.test(cp);
            if (in && start < 0) start = cp;
            if (!in && start >= 0) { b.append(String.format("(0x%X,0x%X),", start, cp - 1)); start = -1; }
        }
        return b.append("]").toString();
    }

    static String lit(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }

    static boolean matches(Pattern p, int cp) { return p.matcher(new String(Character.toChars(cp))).matches(); }

    public static void main(String[] a) throws Exception {
        out.append("//! Generated by `src/regex/RegexTables.java` (`java --add-opens java.base/java.lang=ALL-UNNAMED RegexTables.java`) from the observable\n")
           .append("//! behaviour of OpenJDK ").append(System.getProperty("java.runtime.version")).append(": general categories, scripts and blocks per code\n")
           .append("//! point, the names `UnicodeScript.forName`/`UnicodeBlock.forName` accept, `\\p{..}` membership of the binary and\n")
           .append("//! `java*` properties, case mappings, and the code points a case-insensitive literal or one-character class matches.\n//! Do not edit.\n\n");
        // General categories.
        List<String> gcNames = new ArrayList<>();
        Map<String, Integer> gcIdx = new HashMap<>();
        for (String g : GC) if (g != null) { gcIdx.put(g, gcNames.size()); gcNames.add(g); }
        out.append("pub(crate) static GC_NAMES: &[&str] = &[");
        for (String g : gcNames) out.append(lit(g)).append(",");
        out.append("];\n\n");
        runs("GC", cp -> gcIdx.get(GC[Character.getType(cp)]));
        // Scripts.
        Character.UnicodeScript[] scripts = Character.UnicodeScript.values();
        out.append("pub(crate) static SCRIPT_NAMES: &[&str] = &[");
        for (Character.UnicodeScript s : scripts) out.append(lit(s.name())).append(",");
        out.append("];\n\n");
        out.append("pub(crate) static SCRIPT_ALIASES: &[(&str, u16)] = &[");
        char[] c4 = new char[4];
        for (int i = 0; i < 26 * 26 * 26 * 26; i++) {
            int v = i;
            for (int k = 3; k >= 0; k--) { c4[k] = (char) ('A' + v % 26); v /= 26; }
            String code = new String(c4);
            try {
                Character.UnicodeScript s = Character.UnicodeScript.forName(code);
                if (!s.name().equalsIgnoreCase(code)) out.append("(").append(lit(code)).append(",").append(s.ordinal()).append("),");
            } catch (IllegalArgumentException e) { }
        }
        out.append("];\n\n");
        runs("SCRIPTS", cp -> Character.UnicodeScript.of(cp).ordinal());
        // Blocks: identities from UnicodeBlock.of, names from the static name map UnicodeBlock.forName reads.
        List<Character.UnicodeBlock> blocks = new ArrayList<>();
        Map<Character.UnicodeBlock, Integer> bIdx = new HashMap<>();
        for (int cp = 0; cp <= 0x10FFFF; cp++) {
            Character.UnicodeBlock b = Character.UnicodeBlock.of(cp);
            if (b != null && !bIdx.containsKey(b)) { bIdx.put(b, blocks.size()); blocks.add(b); }
        }
        Map<Character.UnicodeBlock, TreeSet<String>> names = new HashMap<>();
        for (java.lang.reflect.Field f : Character.UnicodeBlock.class.getDeclaredFields()) {
            if (!java.lang.reflect.Modifier.isStatic(f.getModifiers()) || !Map.class.isAssignableFrom(f.getType())) continue;
            f.setAccessible(true);
            for (Map.Entry<?, ?> e : ((Map<?, ?>) f.get(null)).entrySet()) {
                if (!(e.getValue() instanceof Character.UnicodeBlock b)) continue;
                String k = e.getKey().toString();
                // Keep only names forName really accepts for this block.
                try { if (Character.UnicodeBlock.forName(k) == b) names.computeIfAbsent(b, x -> new TreeSet<>()).add(k.toLowerCase(Locale.ROOT)); } catch (IllegalArgumentException ex) { }
            }
        }
        out.append("pub(crate) static BLOCK_NAMES: &[&[&str]] = &[\n");
        for (Character.UnicodeBlock b : blocks) {
            TreeSet<String> ns = names.getOrDefault(b, new TreeSet<>());
            ns.add(b.toString().toLowerCase(Locale.ROOT));
            out.append("&[");
            for (String n : ns) out.append(lit(n)).append(",");
            out.append("],\n");
        }
        out.append("];\n\n");
        runs("BLOCKS", cp -> { Character.UnicodeBlock b = Character.UnicodeBlock.of(cp); return b == null ? -1 : bIdx.get(b); });
        // Properties recorded through java.util.regex itself (flags 0).
        String[] props = {"IsAlphabetic", "IsIdeographic", "IsLowercase", "IsUppercase", "IsWhite_Space", "IsHex_Digit", "IsJoin_Control",
            "IsNoncharacter_Code_Point", "IsEmoji", "IsEmoji_Presentation", "IsEmoji_Modifier", "IsEmoji_Modifier_Base", "IsEmoji_Component",
            "IsExtended_Pictographic", "javaMirrored", "javaUnicodeIdentifierStart", "javaUnicodeIdentifierPart", "javaIdentifierIgnorable",
            "javaJavaIdentifierStart", "javaJavaIdentifierPart", "javaWhitespace", "javaLowerCase", "javaUpperCase", "javaAlphabetic", "javaIdeographic"};
        Map<String, String> seen = new LinkedHashMap<>();
        out.append("pub(crate) static PROPS: &[(&str, &[(u32, u32)])] = &[\n");
        for (String p : props) {
            Pattern pt = Pattern.compile("\\p{" + p + "}");
            out.append("(").append(lit(p)).append(", ").append(ranges(cp -> matches(pt, cp))).append("),\n");
        }
        out.append("];\n\n");
        // Case-insensitive (CASE_INSENSITIVE | UNICODE_CASE) literal and one-char class equivalents.
        TreeSet<Integer> cased = new TreeSet<>();
        for (int cp = 0; cp <= 0x10FFFF; cp++) {
            int u = Character.toUpperCase(cp), l = Character.toLowerCase(cp), t = Character.toTitleCase(cp);
            if (u != cp || l != cp || t != cp) { cased.add(cp); cased.add(u); cased.add(l); cased.add(t); }
        }
        // Character.toUpperCase / toLowerCase of every code point either changes (a case-insensitive range matches c
        // when c, its upper case or the lower case of that is in the range).
        out.append("pub(crate) static CASE_MAP: &[(u32, u32, u32)] = &[\n");
        int m = 0;
        for (int cp = 0; cp <= 0x10FFFF; cp++) {
            int u = Character.toUpperCase(cp), l = Character.toLowerCase(cp);
            if (u != cp || l != cp) { out.append(String.format("(0x%X,0x%X,0x%X),", cp, u, l)); if (++m % 8 == 0) out.append('\n'); }
        }
        out.append("\n];\n\n");
        for (String kind : new String[]{"FOLD_LITERAL", "FOLD_CLASS"}) {
            out.append("pub(crate) static ").append(kind).append(": &[(u32, &[u32])] = &[\n");
            for (int p : cased) {
                String q = String.format("\\x{%X}", p);
                Pattern pt = Pattern.compile(kind.equals("FOLD_LITERAL") ? q : "[" + q + "]", Pattern.CASE_INSENSITIVE | Pattern.UNICODE_CASE);
                StringBuilder b = new StringBuilder();
                for (int c : cased) if (c != p && matches(pt, c)) b.append(String.format("0x%X,", c));
                if (b.length() > 0) out.append(String.format("(0x%X, &[", p)).append(b).append("]),\n");
            }
            out.append("];\n\n");
        }
        System.out.print(out);
    }
}
